"""Entrypoint: runs the Telegram bot and the FastAPI admin UI in one supervised
process (spec section 3, ``bot/main.py``: "runs bot + web in one process group").

Networking modes (see README / spec section 1.2):
  - ``loopback``: uvicorn binds ``0.0.0.0:WEB_PORT`` directly with a self-signed
    TLS cert generated by the installer at ``/etc/tgyt/tls/{selfsigned.crt,key}``.
  - ``hostname``: uvicorn binds ``127.0.0.1:INTERNAL_WEB_PROXY_PORT`` in plain
    HTTP; nginx (installed only in this mode) holds the real Let's Encrypt cert
    and proxies ``WEB_PORT`` -> that internal port.

Note on LOCAL_BOT_API_URL: this bot is built entirely on Kurigram/Pyrogram,
which speaks MTProto directly and never goes through the Bot API HTTP
interface, so there is no "point the client at a local Bot API server" step.
Large (>20MB) downloads instead go through the MTProto relay -- see
``bot/downloader.py`` and the README's "Generating the string session" section.
"""
from __future__ import annotations

import asyncio
import os
import re
import signal
from pathlib import Path

import pyrogram
import structlog
import uvicorn

from bot import security
from bot.config import ENV_FILE, INTERNAL_WEB_PROXY_PORT, apply_db_overrides, settings
from bot.logging_setup import configure_logging
from bot.queue import JobQueue
from db.store import Store

configure_logging(settings.log_level)
log = structlog.get_logger(__name__)

SESSION_DIR = os.path.dirname(settings.db_path) or "."
SELFSIGNED_CERT = "/etc/tgyt/tls/selfsigned.crt"
SELFSIGNED_KEY = "/etc/tgyt/tls/selfsigned.key"


def _blank_admin_password_in_env_file() -> None:
    """Replaces ADMIN_PASSWORD=... with an empty value in the env file, once
    it's been hashed into the DB. Best-effort: a failure here just means the
    plaintext lingers in the env file, not a fatal error."""
    path = Path(ENV_FILE)
    try:
        text = path.read_text(encoding="utf-8")
        new_text, n = re.subn(r"(?m)^ADMIN_PASSWORD=.*$", "ADMIN_PASSWORD=", text)
        if n == 0:
            return
        tmp = path.with_suffix(path.suffix + ".tmp")
        st = path.stat()
        tmp.write_text(new_text, encoding="utf-8")
        os.chmod(tmp, st.st_mode)
        os.replace(tmp, path)
        log.info("main.admin_password_blanked", path=str(path))
    except OSError as exc:
        log.warning("main.blank_admin_password_failed", error=str(exc))


async def _bootstrap_admin(store: Store) -> None:
    if await store.count_app_users() > 0:
        return
    if not settings.admin_password:
        raise SystemExit(
            "FATAL: no admin web-UI user exists yet and ADMIN_PASSWORD is empty. "
            "Set ADMIN_PASSWORD in the env file and restart once to create the first admin."
        )
    pw_hash = security.hash_password(settings.admin_password)
    await store.create_app_user(settings.admin_username, pw_hash, role="owner")
    _blank_admin_password_in_env_file()
    log.info("main.admin_bootstrapped", username=settings.admin_username)


def _build_uvicorn_config(app) -> uvicorn.Config:
    if settings.oauth_mode == "loopback":
        if not (Path(SELFSIGNED_CERT).exists() and Path(SELFSIGNED_KEY).exists()):
            raise SystemExit(
                f"FATAL: OAUTH_MODE=loopback needs a self-signed cert at {SELFSIGNED_CERT} / "
                f"{SELFSIGNED_KEY}. The installer generates this; re-run deploy/install.sh."
            )
        return uvicorn.Config(
            app, host="0.0.0.0", port=settings.web_port,
            ssl_certfile=SELFSIGNED_CERT, ssl_keyfile=SELFSIGNED_KEY,
            log_config=None, access_log=False,
        )
    return uvicorn.Config(
        app, host="127.0.0.1", port=INTERNAL_WEB_PROXY_PORT,
        log_config=None, access_log=False,
    )


async def run() -> None:
    if settings.oauth_mode == "hostname" and not settings.public_host:
        log.error("main.missing_public_host", msg="OAUTH_MODE=hostname requires PUBLIC_HOST to be set.")
    if not settings.project_audited:
        log.warning("main.project_not_audited", msg="Uploads will be forced Private until the audit passes.")

    store = Store(settings.db_path)
    await store.connect()
    await _bootstrap_admin(store)
    await apply_db_overrides(store)

    bot_client = pyrogram.Client(
        "tgyt-bot",
        api_id=settings.api_id,
        api_hash=settings.api_hash,
        bot_token=settings.bot_token,
        workdir=SESSION_DIR,
    )

    user_client: pyrogram.Client | None = None
    if settings.user_session:
        user_client = pyrogram.Client(
            "tgyt-relay",
            api_id=settings.api_id,
            api_hash=settings.api_hash,
            session_string=settings.user_session,
            workdir=SESSION_DIR,
            no_updates=True,
        )

    await bot_client.start()
    if user_client:
        await user_client.start()

    from bot.handlers import caption, channels, ingest, jobs as jobs_handlers, start
    from web.app import create_app

    queue = JobQueue(bot_client, user_client, store)

    start.register(bot_client, store)
    channels.register(bot_client, store)
    ingest.register(bot_client, store, queue)
    caption.register(bot_client, store, queue)
    jobs_handlers.register(bot_client, store, queue)

    await queue.start()

    web_app = create_app(store)
    uvicorn_config = _build_uvicorn_config(web_app)
    uvicorn_server = uvicorn.Server(uvicorn_config)
    web_task = asyncio.create_task(uvicorn_server.serve())

    log.info(
        "main.ready",
        oauth_mode=settings.oauth_mode,
        web_url=settings.ui_base_url,
    )

    stop_event = asyncio.Event()

    def _signal_handler() -> None:
        log.info("main.shutdown_signal")
        stop_event.set()

    loop = asyncio.get_running_loop()
    for sig in (signal.SIGINT, signal.SIGTERM):
        try:
            loop.add_signal_handler(sig, _signal_handler)
        except NotImplementedError:
            pass  # Windows dev environments

    await stop_event.wait()

    log.info("main.shutting_down")
    uvicorn_server.should_exit = True
    await web_task
    await queue.stop()
    await bot_client.stop()
    if user_client:
        await user_client.stop()
    await store.close()
    log.info("main.stopped")


def main() -> None:
    asyncio.run(run())


if __name__ == "__main__":
    main()
